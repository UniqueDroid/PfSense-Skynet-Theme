#!/bin/sh
# Builds css/SkyNet*.css from src/base.css – one file per accent colour.
# Usage: sh build.sh
set -eu
cd "$(dirname "$0")"
mkdir -p css

emit() { # name, label, variables
	out="css/$1.css"
	{
		printf '/*\n * %s.css – SkyNet theme for the pfSense webGUI (%s)\n' "$1" "$2"
		printf ' * https://github.com/UniqueDroid/PfSense-Skynet-Theme\n'
		printf ' * Look derived from the Skynet intranet / ShareOS interface.\n'
		printf ' * Generated by build.sh from src/base.css – edit there, not here.\n */\n\n'
		printf '@import url("/css/pfSense.css");\n'
		printf '@import url("/vendor/jquery-ui/themes/dark-hive/theme.css");\n\n'
		printf ':root {\n%s\n    --sky-ok: #3dff8a; --sky-amber: #e6c25a; --sky-red: #ff5f5f; --sky-errt: #ffb3b3;\n}\n\n' "$3"
		cat src/base.css
	} > "$out"
	echo "built $out"
}

emit SkyNet "blue" \
'    --sky-bg: #06090d; --sky-panel: #0b111a; --sky-ph: #0e1726; --sky-line: #15253b;
    --sky-accent: #3da5ff; --sky-soft: #2b8ad9; --sky-dim: #1d4f80; --sky-rgb: 61, 165, 255;
    --sky-text: #c6dff5; --sky-muted: #6f90ad;'

